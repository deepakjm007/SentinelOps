import { useMemo, useState } from 'react';
import { motion } from 'framer-motion';
import {
  FileBarChart, Download, FileText, Eye, X, Calendar, Filter,
  FileSpreadsheet, AlertTriangle, Server, Shield, CheckCircle, Clock,
} from 'lucide-react';
import { useData } from '@/store/DataContext';
import { GlassCard, PageTransition, SectionHeader, Badge, EmptyState } from '@/components/ui';
import {
  severityColor, severityLabel, osLabel, formatTimestamp, categoryLabel,
} from '@/utils/format';
import { generatePdf, generateCsv } from '@/utils/report';
import { exportToCsv } from '@/utils/format';

interface ReportType {
  id: string;
  title: string;
  description: string;
  icon: React.ReactNode;
  color: string;
}

const REPORT_TYPES: ReportType[] = [
  { id: 'overall', title: 'Overall Security Report', description: 'Comprehensive security overview across all endpoints and events', icon: <Shield className="w-5 h-5" />, color: '#00E5FF' },
  { id: 'windows', title: 'Windows Security Report', description: 'Windows-specific security events, logons, and system activity', icon: <Server className="w-5 h-5" />, color: '#287BFF' },
  { id: 'linux', title: 'Linux Security Report', description: 'Linux authentication, SSH, and system security events', icon: <Server className="w-5 h-5" />, color: '#00E5A8' },
  { id: 'failed_login', title: 'Failed Login Report', description: 'All failed authentication attempts across the infrastructure', icon: <AlertTriangle className="w-5 h-5" />, color: '#FF3B5C' },
  { id: 'successful_login', title: 'Successful Login Report', description: 'All successful authentication events', icon: <CheckCircle className="w-5 h-5" />, color: '#00E5A8' },
  { id: 'suspicious_login', title: 'Suspicious Login Report', description: 'Logins flagged as suspicious by the detection engine', icon: <AlertTriangle className="w-5 h-5" />, color: '#FF8A24' },
  { id: 'endpoint', title: 'Endpoint Monitoring Report', description: 'Endpoint health, status, and activity summary', icon: <Server className="w-5 h-5" />, color: '#8B5CF6' },
  { id: 'alerts', title: 'Security Alert Report', description: 'All security alerts generated by detection rules', icon: <AlertTriangle className="w-5 h-5" />, color: '#FF8A24' },
  { id: 'critical', title: 'Critical Threat Report', description: 'Critical-severity threats requiring immediate attention', icon: <AlertTriangle className="w-5 h-5" />, color: '#FF3B5C' },
  { id: 'fim', title: 'File Integrity Report', description: 'File integrity monitoring events and sensitive file changes', icon: <FileText className="w-5 h-5" />, color: '#FF8A24' },
  { id: 'detection_rules', title: 'Detection Rule Report', description: 'Detection rule execution history and alert generation', icon: <Shield className="w-5 h-5" />, color: '#8B5CF6' },
  { id: 'use_cases', title: 'Use Case Report', description: 'Use case implementation status and results', icon: <FileText className="w-5 h-5" />, color: '#287BFF' },
  { id: 'kali', title: 'Kali Activity Report', description: 'Suspicious activity from Kali Linux endpoints', icon: <AlertTriangle className="w-5 h-5" />, color: '#E879F9' },
  { id: 'daily', title: 'Daily Security Summary', description: 'Summary of security events for a single day', icon: <Clock className="w-5 h-5" />, color: '#00E5FF' },
  { id: 'weekly', title: 'Weekly Security Summary', description: 'Weekly security overview and trend analysis', icon: <Clock className="w-5 h-5" />, color: '#287BFF' },
  { id: 'monthly', title: 'Monthly Security Summary', description: 'Monthly security posture and incident summary', icon: <Clock className="w-5 h-5" />, color: '#8B5CF6' },
];

export function ReportsPage() {
  const { data } = useData();
  const [selectedType, setSelectedType] = useState<string>('overall');
  const [startDate, setStartDate] = useState('');
  const [endDate, setEndDate] = useState('');
  const [endpoint, setEndpoint] = useState('all');
  const [operatingSystem, setOperatingSystem] = useState('all');
  const [severity, setSeverity] = useState('all');
  const [alertStatus, setAlertStatus] = useState('all');
  const [previewOpen, setPreviewOpen] = useState(false);
  const [generating, setGenerating] = useState(false);

  const reportType = REPORT_TYPES.find(r => r.id === selectedType)!;

  // Compute filtered data for preview
  const previewData = useMemo(() => {
    let logs = [...data.logs];
    let alerts = [...data.alerts];

    // Apply date filters
    if (startDate) logs = logs.filter(l => l.timestamp >= startDate);
    if (endDate) logs = logs.filter(l => l.timestamp <= endDate + 'T23:59:59');
    if (startDate) alerts = alerts.filter(a => a.detection_timestamp >= startDate);
    if (endDate) alerts = alerts.filter(a => a.detection_timestamp <= endDate + 'T23:59:59');

    // Apply type-specific filters
    switch (selectedType) {
      case 'windows': logs = logs.filter(l => l.operating_system === 'windows'); break;
      case 'linux': logs = logs.filter(l => l.operating_system === 'linux' || l.operating_system === 'kali'); break;
      case 'failed_login': logs = logs.filter(l => l.event_outcome === 'failure'); break;
      case 'successful_login': logs = logs.filter(l => l.event_outcome === 'success' && (l.event_id === 4624 || l.event_id === 2401)); break;
      case 'suspicious_login': alerts = alerts.filter(a => a.title.toLowerCase().includes('suspicious') || a.title.toLowerCase().includes('brute')); break;
      case 'critical': alerts = alerts.filter(a => a.severity === 'critical'); break;
      case 'fim': logs = logs.filter(l => l.event_category === 'file_integrity'); break;
      case 'kali': logs = logs.filter(l => l.operating_system === 'kali'); break;
      case 'alerts': break;
      default: break;
    }

    if (endpoint !== 'all') { logs = logs.filter(l => l.hostname === endpoint); alerts = alerts.filter(a => a.endpoint === endpoint); }
    if (operatingSystem !== 'all') { logs = logs.filter(l => l.operating_system === operatingSystem); }
    if (severity !== 'all') { logs = logs.filter(l => l.severity === severity); alerts = alerts.filter(a => a.severity === severity); }
    if (alertStatus !== 'all') alerts = alerts.filter(a => a.status === alertStatus);

    // For alert-type reports, logs are related to alerts
    if (selectedType === 'alerts' || selectedType === 'critical' || selectedType === 'suspicious_login') {
      return { logs: [], alerts, focus: 'alerts' as const };
    }

    return { logs, alerts, focus: 'logs' as const };
  }, [data, selectedType, startDate, endDate, endpoint, operatingSystem, severity, alertStatus]);

  const hasResults = previewData.focus === 'alerts' ? previewData.alerts.length > 0 : previewData.logs.length > 0;

  const handleGeneratePdf = () => {
    setGenerating(true);
    setTimeout(() => {
      const opts = {
        reportType: selectedType, reportTitle: reportType.title,
        startDate, endDate, endpoint, operatingSystem, severity, alertStatus,
      };
      const doc = generatePdf(data, opts);
      doc.save(`SentinelOps_${selectedType}_${Date.now()}.pdf`);
      setGenerating(false);
    }, 300);
  };

  const handleDownloadCsv = () => {
    const opts = {
      reportType: selectedType, reportTitle: reportType.title,
      startDate, endDate, endpoint, operatingSystem, severity, alertStatus,
    };
    const { headers, rows } = generateCsv(data, opts);
    if (rows.length === 0) {
      exportToCsv(`SentinelOps_${selectedType}_${Date.now()}.csv`, ['Info'], [['No records match the selected filters']]);
      return;
    }
    exportToCsv(`SentinelOps_${selectedType}_${Date.now()}.csv`, headers, rows);
  };

  return (
    <PageTransition>
      <SectionHeader
        title="Reports"
        subtitle="Generate professional security reports — PDF & CSV export"
        icon={<FileBarChart className="w-5 h-5" />}
      />

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-4">
        {/* Left: Report type selection */}
        <div className="lg:col-span-1 space-y-4">
          <GlassCard className="p-4">
            <h3 className="text-sm font-semibold text-white mb-3">Report Type</h3>
            <div className="space-y-1.5 max-h-[400px] overflow-y-auto scrollbar-thin">
              {REPORT_TYPES.map(r => (
                <button key={r.id} onClick={() => setSelectedType(r.id)}
                  className={`w-full flex items-start gap-3 p-2.5 rounded-lg text-left transition-all ${selectedType === r.id ? 'bg-cyan-glow/10 border border-cyan-glow/30' : 'border border-transparent hover:bg-white/5'}`}>
                  <div className="w-8 h-8 rounded-lg flex items-center justify-center flex-shrink-0" style={{ backgroundColor: `${r.color}15`, color: r.color }}>
                    {r.icon}
                  </div>
                  <div className="min-w-0">
                    <div className={`text-xs font-medium ${selectedType === r.id ? 'text-cyan-glow' : 'text-white'}`}>{r.title}</div>
                    <div className="text-[10px] text-slate-500 mt-0.5 line-clamp-2">{r.description}</div>
                  </div>
                </button>
              ))}
            </div>
          </GlassCard>
        </div>

        {/* Right: Configuration & preview */}
        <div className="lg:col-span-2 space-y-4">
          {/* Configuration */}
          <GlassCard className="p-5">
            <h3 className="text-sm font-semibold text-white mb-4 flex items-center gap-2">
              <Filter className="w-4 h-4 text-cyan-glow" /> Report Configuration
            </h3>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-3 mb-4">
              <FormField label="Start Date">
                <input type="date" value={startDate} onChange={e => setStartDate(e.target.value)}
                  className="w-full px-3 py-2 bg-deep-navy/60 border border-neon-blue/15 rounded-lg text-sm text-white focus:outline-none focus:border-cyan-glow/40" />
              </FormField>
              <FormField label="End Date">
                <input type="date" value={endDate} onChange={e => setEndDate(e.target.value)}
                  className="w-full px-3 py-2 bg-deep-navy/60 border border-neon-blue/15 rounded-lg text-sm text-white focus:outline-none focus:border-cyan-glow/40" />
              </FormField>
              <FormField label="Endpoint">
                <select value={endpoint} onChange={e => setEndpoint(e.target.value)}
                  className="w-full px-3 py-2 bg-deep-navy/60 border border-neon-blue/15 rounded-lg text-sm text-white cursor-pointer focus:outline-none focus:border-cyan-glow/40">
                  <option value="all" className="bg-deep-navy">All Endpoints</option>
                  {data.endpoints.map(ep => <option key={ep.id} value={ep.name} className="bg-deep-navy">{ep.name}</option>)}
                </select>
              </FormField>
              <FormField label="Operating System">
                <select value={operatingSystem} onChange={e => setOperatingSystem(e.target.value)}
                  className="w-full px-3 py-2 bg-deep-navy/60 border border-neon-blue/15 rounded-lg text-sm text-white cursor-pointer focus:outline-none focus:border-cyan-glow/40">
                  <option value="all" className="bg-deep-navy">All OS</option>
                  <option value="windows" className="bg-deep-navy">Windows</option>
                  <option value="linux" className="bg-deep-navy">Linux</option>
                  <option value="kali" className="bg-deep-navy">Kali Linux</option>
                </select>
              </FormField>
              <FormField label="Severity">
                <select value={severity} onChange={e => setSeverity(e.target.value)}
                  className="w-full px-3 py-2 bg-deep-navy/60 border border-neon-blue/15 rounded-lg text-sm text-white cursor-pointer focus:outline-none focus:border-cyan-glow/40">
                  <option value="all" className="bg-deep-navy">All Severities</option>
                  <option value="critical" className="bg-deep-navy">Critical</option>
                  <option value="high" className="bg-deep-navy">High</option>
                  <option value="medium" className="bg-deep-navy">Medium</option>
                  <option value="low" className="bg-deep-navy">Low</option>
                </select>
              </FormField>
              <FormField label="Alert Status">
                <select value={alertStatus} onChange={e => setAlertStatus(e.target.value)}
                  className="w-full px-3 py-2 bg-deep-navy/60 border border-neon-blue/15 rounded-lg text-sm text-white cursor-pointer focus:outline-none focus:border-cyan-glow/40">
                  <option value="all" className="bg-deep-navy">All Status</option>
                  <option value="new" className="bg-deep-navy">New</option>
                  <option value="active" className="bg-deep-navy">Active</option>
                  <option value="acknowledged" className="bg-deep-navy">Acknowledged</option>
                  <option value="resolved" className="bg-deep-navy">Resolved</option>
                </select>
              </FormField>
            </div>

            {/* Result summary */}
            <div className="flex items-center gap-2 p-2.5 bg-deep-navy/40 rounded-lg mb-4">
              <FileText className="w-4 h-4 text-cyan-glow" />
              <span className="text-xs text-slate-400">
                {previewData.focus === 'alerts'
                  ? `${previewData.alerts.length} alerts match the selected filters`
                  : `${previewData.logs.length} log records match the selected filters`}
              </span>
              {hasResults && <Badge color="#00E5A8">Data Available</Badge>}
            </div>

            {/* Action buttons */}
            <div className="flex flex-wrap gap-2">
              <button onClick={() => setPreviewOpen(true)} disabled={!hasResults}
                className="flex items-center gap-1.5 px-4 py-2 bg-neon-blue/10 border border-neon-blue/30 rounded-lg text-sm text-neon-blue hover:bg-neon-blue/20 transition-colors disabled:opacity-40 disabled:cursor-not-allowed">
                <Eye className="w-4 h-4" /> Preview
              </button>
              <button onClick={handleGeneratePdf} disabled={!hasResults || generating}
                className="flex items-center gap-1.5 px-4 py-2 bg-critical/10 border border-critical/30 rounded-lg text-sm text-critical hover:bg-critical/20 transition-colors disabled:opacity-40 disabled:cursor-not-allowed">
                <Download className="w-4 h-4" /> {generating ? 'Generating...' : 'Download PDF'}
              </button>
              <button onClick={handleDownloadCsv} disabled={!hasResults}
                className="flex items-center gap-1.5 px-4 py-2 bg-success/10 border border-success/30 rounded-lg text-sm text-success hover:bg-success/20 transition-colors disabled:opacity-40 disabled:cursor-not-allowed">
                <FileSpreadsheet className="w-4 h-4" /> Download CSV
              </button>
            </div>

            {!hasResults && (
              <div className="mt-3 text-xs text-alert-orange bg-alert-orange/10 border border-alert-orange/20 rounded-lg px-3 py-2">
                No records match the selected filters. Adjust filters or try a different date range.
              </div>
            )}
          </GlassCard>

          {/* Quick stats for selected report */}
          <GlassCard className="p-5">
            <h3 className="text-sm font-semibold text-white mb-3 flex items-center gap-2">
              <FileBarChart className="w-4 h-4 text-cyan-glow" /> {reportType.title} — Summary
            </h3>
            <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
              <SummaryStat label="Total Logs" value={previewData.logs.length} color="#00E5FF" />
              <SummaryStat label="Total Alerts" value={previewData.alerts.length} color="#FF8A24" />
              <SummaryStat label="Critical" value={previewData.alerts.filter(a => a.severity === 'critical').length} color="#FF3B5C" />
              <SummaryStat label="Resolved" value={previewData.alerts.filter(a => a.status === 'resolved').length} color="#00E5A8" />
            </div>
          </GlassCard>
        </div>
      </div>

      {/* Preview modal */}
      {previewOpen && (
        <PreviewModal title={reportType.title} data={previewData} onClose={() => setPreviewOpen(false)} />
      )}
    </PageTransition>
  );
}

function PreviewModal({ title, data, onClose }: {
  title: string;
  data: { logs: ReturnType<typeof useData>['data']['logs']; alerts: ReturnType<typeof useData>['data']['alerts']; focus: 'logs' | 'alerts' };
  onClose: () => void;
}) {
  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
      className="fixed inset-0 bg-black/70 z-[60] flex items-center justify-center p-4" onClick={onClose}>
      <motion.div initial={{ scale: 0.95, y: 20 }} animate={{ scale: 1, y: 0 }}
        className="glass-strong rounded-xl border border-neon-blue/20 max-w-4xl w-full max-h-[88vh] overflow-y-auto scrollbar-thin"
        onClick={e => e.stopPropagation()}>
        <div className="flex items-center justify-between p-4 border-b border-neon-blue/10 sticky top-0 bg-deep-navy/95 backdrop-blur z-10">
          <div className="flex items-center gap-3">
            <FileBarChart className="w-5 h-5 text-cyan-glow" />
            <div>
              <h3 className="text-white font-semibold text-sm">{title} — Preview</h3>
              <p className="text-xs text-slate-500">Generated {formatTimestamp(new Date().toISOString())}</p>
            </div>
          </div>
          <button onClick={onClose} className="text-slate-500 hover:text-white"><X className="w-5 h-5" /></button>
        </div>

        <div className="p-5">
          {data.focus === 'alerts' ? (
            data.alerts.length === 0 ? (
              <EmptyState icon={<FileBarChart className="w-8 h-8" />} title="No alerts match filters" message="Adjust your filters to see results." />
            ) : (
              <table className="w-full text-xs">
                <thead>
                  <tr className="border-b border-neon-blue/10 text-slate-400">
                    <th className="px-2 py-2 text-left">Alert ID</th>
                    <th className="px-2 py-2 text-left">Title</th>
                    <th className="px-2 py-2 text-left">Severity</th>
                    <th className="px-2 py-2 text-left">Endpoint</th>
                    <th className="px-2 py-2 text-left">Status</th>
                    <th className="px-2 py-2 text-left">Timestamp</th>
                  </tr>
                </thead>
                <tbody>
                  {data.alerts.map(a => (
                    <tr key={a.id} className="border-b border-neon-blue/5">
                      <td className="px-2 py-2 font-mono text-cyan-glow">{a.alert_id}</td>
                      <td className="px-2 py-2 text-white">{a.title.substring(0, 50)}</td>
                      <td className="px-2 py-2"><span style={{ color: severityColor(a.severity) }}>{severityLabel(a.severity)}</span></td>
                      <td className="px-2 py-2 text-slate-300">{a.endpoint}</td>
                      <td className="px-2 py-2 text-slate-300 capitalize">{a.status}</td>
                      <td className="px-2 py-2 text-slate-500">{formatTimestamp(a.detection_timestamp)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )
          ) : (
            data.logs.length === 0 ? (
              <EmptyState icon={<FileBarChart className="w-8 h-8" />} title="No logs match filters" message="Adjust your filters to see results." />
            ) : (
              <table className="w-full text-xs">
                <thead>
                  <tr className="border-b border-neon-blue/10 text-slate-400">
                    <th className="px-2 py-2 text-left">Timestamp</th>
                    <th className="px-2 py-2 text-left">Hostname</th>
                    <th className="px-2 py-2 text-left">Event ID</th>
                    <th className="px-2 py-2 text-left">User</th>
                    <th className="px-2 py-2 text-left">Source IP</th>
                    <th className="px-2 py-2 text-left">Severity</th>
                    <th className="px-2 py-2 text-left">Message</th>
                  </tr>
                </thead>
                <tbody>
                  {data.logs.slice(0, 50).map(l => (
                    <tr key={l.id} className="border-b border-neon-blue/5">
                      <td className="px-2 py-2 text-slate-400 font-mono">{formatTimestamp(l.timestamp)}</td>
                      <td className="px-2 py-2 text-white">{l.hostname}</td>
                      <td className="px-2 py-2 font-mono text-cyan-glow">{l.event_id}</td>
                      <td className="px-2 py-2 text-slate-300">{l.username}</td>
                      <td className="px-2 py-2 text-slate-400 font-mono">{l.source_ip}</td>
                      <td className="px-2 py-2"><span style={{ color: severityColor(l.severity) }}>{severityLabel(l.severity)}</span></td>
                      <td className="px-2 py-2 text-slate-300 max-w-xs truncate">{l.message.substring(0, 50)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )
          )}
          {data.focus === 'logs' && data.logs.length > 50 && (
            <div className="text-center text-xs text-slate-500 mt-4">Showing 50 of {data.logs.length} records. Download PDF/CSV for full report.</div>
          )}
        </div>
      </motion.div>
    </motion.div>
  );
}

function FormField({ label, children }: { label: string; children: React.ReactNode }) {
  return <div><label className="text-xs text-slate-400 mb-1.5 block">{label}</label>{children}</div>;
}

function SummaryStat({ label, value, color }: { label: string; value: number; color: string }) {
  return (
    <div className="p-3 bg-deep-navy/40 rounded-lg border border-neon-blue/5">
      <div className="text-2xl font-bold" style={{ color }}>{value}</div>
      <div className="text-xs text-slate-500 mt-1">{label}</div>
    </div>
  );
}
